function scanDirectory(dir, findings = []) {
  const IGNORE = new Set(['node_modules', '.git', '.next', 'dist', 'build', '.venv']);
  const files = fs.readdirSync(dir);

  for (const f of files) {
    if (IGNORE.has(f)) continue;
    const fullPath = path.join(dir, f);
    const stat = fs.statSync(fullPath);

    if (stat.isDirectory()) {
      scanDirectory(fullPath, findings);
    } else {
      let content = null;
      try {
        content = fs.readFileSync(fullPath, 'utf8');
      } catch (e) {
        continue;
      }

      for (const check of VIBE_CHECKS) {
        if (check.customCheck) {
          const customHits = check.customCheck(fullPath, content);
          for (const hit of customHits) {
            findings.push({
              check,
              file: path.relative(process.cwd(), fullPath),
              lineNum: hit.lineNum,
              lineSnippet: hit.lineSnippet
            });
          }
          continue;
        }

        if (!check.fileFilter(f)) continue;

        const lines = content.split('\n');
        lines.forEach((line, index) => {
          check.regex.lastIndex = 0;
          if (check.regex.test(line)) {
            findings.push({
              check,
              file: path.relative(process.cwd(), fullPath),
              lineNum: index + 1,
              lineSnippet: line.trim()
            });
          }
        });
      }
    }
  }

  return findings;
}

// Live Black-Box Attack Simulator (Probes public URL / Supabase endpoint anonymously)
