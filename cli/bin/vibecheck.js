    console.log(`  ${COLORS.cyan}File:${COLORS.reset} ${f.file}:${f.lineNum}`);
    console.log(`  ${COLORS.dim}Code: ${f.lineSnippet.slice(0, 80)}${f.lineSnippet.length > 80 ? '...' : ''}${COLORS.reset}`);
