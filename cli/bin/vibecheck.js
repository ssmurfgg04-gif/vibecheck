function fetchJson(urlStr, anonKey) {
  return new Promise((resolve, reject) => {
    const u = new URL(urlStr);
    const options = {
      headers: {
        'apikey': anonKey || '',
        'Authorization': `Bearer ${anonKey || ''}`
      },
      timeout: 5000
    };
    const req = (u.protocol === 'https:' ? https : http).get(urlStr, options, (res) => {
      let data = '';
      res.on('data', chunk => data += chunk);
      res.on('end', () => {
        try {
          resolve(JSON.parse(data));
        } catch (e) {
          resolve(null);
        }
      });
    });
    req.on('error', reject);
    req.on('timeout', () => { req.destroy(); reject(new Error('timeout')); });
  });
}

